def main():
    excel_path = "workflow-fixes/pipeline_result.xlsx"
    print(f"Loading {excel_path}...")
    wb = openpyxl.load_workbook(excel_path)
    ws = wb["nodejs"]

    # Map merged row ranges from Column A (col 1)
    col_a_ranges = {r.min_row: r.max_row for r in ws.merged_cells.ranges if r.min_col == 1 and r.max_col == 1}

    updated_count = 0
    row = 2
    while row <= ws.max_row:
        yaml_file = ws.cell(row=row, column=3).value
        end_row = col_a_ranges.get(row, row)

        if not yaml_file:
            row = end_row + 1
            continue

        yaml_clean = str(yaml_file).strip()
        if yaml_clean in DATA:
            entry = DATA[yaml_clean]
            print(f"Populating [{yaml_clean}] at rows {row}-{end_row} (cols 8-32)...")

            for col_idx in range(8, 33):
                val = entry.get(col_idx, "")
                top_cell = ws.cell(row=row, column=col_idx)
                top_cell.value = val
                top_cell.alignment = Alignment(vertical="center", wrap_text=True)

                # Clear remaining sub-cells in multi-row blocks
                for sub_r in range(row + 1, end_row + 1):
                    sub_cell = ws.cell(row=sub_r, column=col_idx)
                    sub_cell.value = None

                # Merge range across rows if block spans multiple rows
                if end_row > row:
                    ws.merge_cells(start_row=row, start_column=col_idx, end_row=end_row, end_column=col_idx)

            updated_count += 1
        else:
            print(f"Warning: No data definition found for {yaml_clean} (row {row})")

        row = end_row + 1

    wb.save(excel_path)
    print(f"\nSUCCESS: Successfully populated columns 8-32 for all {updated_count} workflows in 'nodejs' sheet!")


if __name__ == "__main__":
    main()
